//! Own-root client-current physics records. This is the same restricted branch
//! as scripts/live_character_physics.py; successful encoding/sending does not
//! establish peer acceptance or support for motors and dependent bodies.

use crate::physics_codec::{encode_position, encode_velocity};

pub const APPLICATION: u8 = 4;
pub const CHANNEL: u8 = 6;
// Clock channels use 2/4 and the ping writer uses 6. Outgoing IDs are local.
pub const WIRE_ID: u32 = 8;

fn reference(output: &mut Vec<u8>, scope: u32, index: u32) -> Result<(), &'static str> {
    if scope == 0 || scope == u32::MAX {
        return Err("physics-root-reference-invalid");
    }
    let mut word = scope;
    while word >= 128 {
        output.push((word as u8 & 0x7f) | 0x80);
        word >>= 7;
    }
    output.push(word as u8);
    output.extend_from_slice(&index.to_le_bytes());
    Ok(())
}

/// Encode the owned root in world coordinates with compact velocities and the
/// native identity rotation selector. No received world value is overwritten.
pub fn encode_root_frame(
    root: u64,
    timestamp_ms: u64,
    sequence: u64,
    position: [f64; 3],
    velocity: [f64; 3],
    grounded: bool,
) -> Result<Vec<u8>, &'static str> {
    if sequence == 0 {
        return Err("physics-sequence-invalid");
    }
    let mut output = Vec::with_capacity(64);
    output.push(0x1b);
    output.extend_from_slice(&timestamp_ms.to_le_bytes());
    output.extend_from_slice(&sequence.to_le_bytes());
    output.push(0x85);
    reference(&mut output, (root >> 32) as u32, root as u32)?;
    output.extend_from_slice(&[0, 1]); // No cached block; current body present.
    output.push(if grounded { 8 } else { 5 }); // Running / Freefall.
    output.push(0); // Empty motor block for the supported own-root branch.
    output.push(1); // Identity rotation; position and both velocities present.
    output.extend(encode_position(position).map_err(|_| "physics-position-invalid")?);
    output.extend(encode_velocity(velocity).map_err(|_| "physics-velocity-invalid")?);
    output.push(0); // Zero angular velocity.
    output.push(0); // Current record's null world-coordinate reference.
    output.push(0); // End dependent bodies.
    output.push(0); // End top-level roots.
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_missing_root_and_nonfinite_vectors() {
        for root in [0, 1, u64::MAX] {
            assert!(encode_root_frame(root, 1, 1, [0.; 3], [0.; 3], false).is_err());
        }
        assert!(encode_root_frame(1 << 32 | 7, 1, 1, [f64::NAN; 3], [0.; 3], false).is_err());
        assert!(encode_root_frame(1 << 32 | 7, 1, 1, [0.; 3], [f64::INFINITY; 3], false).is_err());
    }

    #[test]
    fn independent_python_codec_fixtures() {
        // Generated by the existing Python header/root/current/vector codecs,
        // not by this encoder. Inputs contain no captured session credentials.
        let cases = include_str!("../tests/fixtures/physics-root-frames.json");
        let cases: serde_json::Value = serde_json::from_str(cases).unwrap();
        for case in cases.as_array().unwrap() {
            let vector = |name: &str| std::array::from_fn(|i| case[name][i].as_f64().unwrap());
            let encoded = encode_root_frame(
                case["root"].as_u64().unwrap(),
                case["timestamp_ms"].as_u64().unwrap(),
                case["sequence"].as_u64().unwrap(),
                vector("position"),
                vector("velocity"),
                case["grounded"].as_bool().unwrap(),
            )
            .unwrap();
            let hex: String = encoded.iter().map(|b| format!("{b:02x}")).collect();
            assert_eq!(hex, case["hex"].as_str().unwrap());
        }
    }
}
