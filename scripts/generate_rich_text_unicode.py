"""Generate the native RichText case tables from Unicode 17.0.0 UCD files.

Pass a directory containing UnicodeData.txt, SpecialCasing.txt, and license.txt.
The generated include is checked in so native builds need no downloads.
"""

import argparse
from pathlib import Path


def generate(ucd):
    uppercase = {}
    marks = []
    for line in (ucd / 'UnicodeData.txt').read_text(encoding='utf-8').splitlines():
        code, _, category, *fields = line.split(';')
        point = int(code, 16)
        if category.startswith('M'):
            if marks and marks[-1][1] + 1 == point:
                marks[-1][1] = point
            else:
                marks.append([point, point])
        if fields[9]:
            uppercase[point] = (int(fields[9], 16),)

    for line in (ucd / 'SpecialCasing.txt').read_text(encoding='utf-8').splitlines():
        record = line.partition('#')[0].strip()
        if record:
            code, _, _, upper, condition, *_ = map(str.strip, record.split(';'))
            if not condition:
                uppercase[int(code, 16)] = tuple(int(point, 16) for point in upper.split())

    ranges = []
    expansions = []
    for point, mapped in sorted(uppercase.items()):
        if len(mapped) != 1:
            expansions.append((point, mapped))
            continue
        delta = mapped[0] - point
        if not delta:
            continue
        if ranges:
            first, last, step, previous_delta = ranges[-1]
            gap = point - last
            if delta == previous_delta and gap in (1, 2) and (first == last or step == gap):
                ranges[-1] = (first, point, gap, delta)
                continue
        ranges.append((point, point, 1, delta))

    license_text = (ucd / 'license.txt').read_text(encoding='utf-8').strip()
    print('// Generated by scripts/generate_rich_text_unicode.py from Unicode 17.0.0.')
    print('// https://www.unicode.org/Public/17.0.0/ucd/')
    print(f'/*\n{license_text}\n*/')
    print('constexpr struct {uint32_t first,last,step;int delta;} uppercase_ranges[]={')
    for first, last, step, delta in ranges:
        print(f'    {{{first:#x},{last:#x},{step},{delta}}},')
    print('};\nconstexpr struct {uint32_t point,mapped[3];} uppercase_expansions[]={')
    for point, mapped in expansions:
        assert 2 <= len(mapped) <= 3
        values = ','.join(hex(value) for value in mapped)
        print(f'    {{{point:#x},{{{values}}}}},')
    print('};\nconstexpr struct {uint32_t first,last;} combining_mark_ranges[]={')
    for first, last in marks:
        print(f'    {{{first:#x},{last:#x}}},')
    print('};')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ucd', type=Path)
    generate(parser.parse_args().ucd)
